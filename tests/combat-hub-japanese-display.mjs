assert.match(src,/jpDisplay\(row\.b\)/);
assert.match(src,/jpDisplay\(D\.name\|\|''\)/);
assert.match(src,/function largeNextTitle\(next\)/);
assert.match(src,/jpDisplay\(next\?\.name\|\|'次大会'\)/);
